package sample;

/**
 * Launcher dient als Startklasse für die ausführbare JAR-Datei.
 * <p>
 * Die Klasse ruft die eigentliche JavaFX-Startklasse {@link Starter} auf.
 */
public class Launcher {

    /**
     *
     * Startet die Anwendung über {@link Starter#main(String[])}.
     * @param args Startargumente der Anwendung
     */
    public static void main(String[] args) {
        Starter.main(args);
    }
}
